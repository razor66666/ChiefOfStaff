import Foundation

/// Manages local offline persistence and background flushing for captured payloads.
public class QueueManager: ObservableObject {
    public static let shared = QueueManager()
    
    @Published public private(set) var pendingQueueCount: Int = 0
    @Published public private(set) var isSyncing: Bool = false
    
    private let queueDirectory: URL
    private let fileManager = FileManager.default

    public init() {
        // Locate local App Sandbox Documents/Queue directory
        let paths = fileManager.urls(for: .documentDirectory, in: .userDomainMask)
        let documentsDirectory = paths[0]
        self.queueDirectory = documentsDirectory.appendingPathComponent("Queue", isDirectory: true)
        
        createQueueDirectoryIfNeeded()
        refreshQueueCount()
    }
    
    // MARK: - Directory Setup
    private func createQueueDirectoryIfNeeded() {
        if !fileManager.fileExists(atPath: queueDirectory.path) {
            do {
                try fileManager.createDirectory(at: queueDirectory, withIntermediateDirectories: true, attributes: nil)
            } catch {
                print("[QueueManager] Error creating queue directory: \(error.localizedDescription)")
            }
        }
    }

    // MARK: - Local Persistence (Enqueue)
    
    /// Persists a payload to local disk storage as an offline queue item.
    /// - Parameter payload: The CapturePayload generated by the UI.
    /// - Returns: Bool indicating if local disk write succeeded.
    @discardableResult
    public func enqueue(_ payload: CapturePayload) -> Bool {
        let fileURL = queueDirectory.appendingPathComponent("\(payload.id.uuidString).json")
        
        do {
            let encoder = JSONEncoder()
            encoder.outputFormatting = .prettyPrinted
            encoder.dateEncodingStrategy = .iso8601
            
            let data = try encoder.encode(payload)
            try data.write(to: fileURL, options: [.atomic, .completeFileProtection])
            
            print("[QueueManager] Payload \(payload.id) enqueued locally to \(fileURL.lastPathComponent)")
            refreshQueueCount()
            return true
        } catch {
            print("[QueueManager] Failed to enqueue payload \(payload.id): \(error.localizedDescription)")
            return false
        }
    }

    // MARK: - Queue Inspection & Fetch
    
    /// Reads all pending local payloads from disk.
    public func fetchAllPendingPayloads() -> [CapturePayload] {
        guard let fileURLs = try? fileManager.contentsOfDirectory(at: queueDirectory, includingPropertiesForKeys: nil) else {
            return []
        }
        
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        
        var payloads: [CapturePayload] = []
        
        for url in fileURLs where url.pathExtension == "json" {
            if let data = try? Data(contentsOf: url),
               let payload = try? decoder.decode(CapturePayload.self, from: data) {
                payloads.append(payload)
            }
        }
        
        return payloads.sorted(by: { $0.timestamp < $1.timestamp })
    }

    /// Updates the published queue counter for UI binding.
    public func refreshQueueCount() {
        DispatchQueue.main.async {
            let payloads = self.fetchAllPendingPayloads()
            self.pendingQueueCount = payloads.count
        }
    }

    // MARK: - Queue Flush (Purge after successful dispatch)
    
    /// Removes a payload from the local queue directory upon successful server ingestion.
    public func dequeue(id: UUID) {
        let fileURL = queueDirectory.appendingPathComponent("\(id.uuidString).json")
        if fileManager.fileExists(atPath: fileURL.path) {
            do {
                try fileManager.removeItem(at: fileURL)
                print("[QueueManager] Successfully dequeued payload: \(id)")
                refreshQueueCount()
            } catch {
                print("[QueueManager] Error removing dequeued file \(id): \(error.localizedDescription)")
            }
        }
    }
}